def main() -> None:
    assert 100 <= len(CASES) <= 150
    ids = [case["id"] for case in CASES]
    questions = [case["question"].casefold() for case in CASES]
    assert len(ids) == len(set(ids)), "case ids must be unique"
    assert len(questions) == len(set(questions)), "questions must be unique"
    OUTPUT.write_text(
        "\n".join(json.dumps(case, ensure_ascii=False, separators=(",", ":")) for case in CASES) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(CASES)} cases to {OUTPUT}")


if __name__ == "__main__":
    main()
