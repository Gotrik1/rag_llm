"""Shared source-entailment instructions; not a deterministic truth checker.

These rules distinguish relationships, not document names or domain keywords.
Model compliance still needs measured factual and correct-fact-retention tests.
"""


_RELATIONS = """Проверяй смысловые связи, а не только совпадение терминов.
Для каждого утверждения сопоставь с источником действующее лицо, действие, объект, происхождение данных, способ выполнения, условие, область действия, время и единицы — только те элементы, которые утверждаются в ответе.
Безличная или пассивная запись действия сама по себе не устанавливает неназванного исполнителя и не означает автоматизацию либо ручное выполнение. Явно названный в источнике способ или исполнитель, наоборот, сохраняется.
Источник данных не становится исполнителем операции. Перенос данных не доказывает их измерение или получение тем же участником. Роль, способ и условие одной строки таблицы или одного этапа не переносятся на другую строку или этап без исходной связи.
Достаточное условие не становится необходимым или единственным. Из частного случая нельзя вывести правило для всех случаев, а из перечисления нескольких элементов — отсутствие остальных, если полнота не установлена.
Определение понятия не устанавливает разрешение, обязанность или условие допуска. Количество, цена за единицу и итоговая сумма — разные величины; сохраняй их исходные роли и единицы.
Логический вывод из нескольких явных исходных условий разрешён. Для расчёта сначала должны быть установлены связывающее величины правило и условия его применимости. Возможность арифметической операции сама по себе не доказывает, что полученный результат описывает фактическую ситуацию.
Не достраивай недостающие связи по обычной практике, предположению о работе системы или общим знаниям. Отсутствие подтверждения не является доказательством противоположного утверждения.
"""


def source_relation_instructions(purpose: str) -> str:
    """Keep writer and judge aligned without supplying any case-specific verdict."""
    if purpose == "writer":
        return _RELATIONS + (
            "Если источник подтверждает действие, но не называет исполнителя или способ, "
            "сообщи подтверждённое действие и кратко обозначь именно этот пробел. "
            "Не заменяй подтверждённую часть целиком отказом и не заполняй пробел догадкой.\n"
        )
    if purpose == "judge":
        return _RELATIONS + (
            "supported требует подтверждения всех утверждаемых смысловых связей фрагмента. "
            "Дословная цитата с добавленным недоказанным толкованием не подтверждает весь фрагмент: "
            "при частичной поддержке ставь uncertain. Для отсутствующей исходной связи используй "
            "unsupported или uncertain; contradicted требует действительно несовместимых исходных "
            "сведений, а не просто отсутствия доказательства. Не путай это с соответствием вопросу: "
            "ошибочное утверждение может отвечать предмету вопроса.\n"
        )
    raise ValueError("Expected writer or judge source-relation contract")
