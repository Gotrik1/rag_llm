def verify_sources() -> list[dict]:
    from docx_parser import read_docx_text
    from evidence_selection import SectionEvidenceIndex
    from rag_agent import build_section_documents
    directory = ROOT / "output/diagnostics/2026-10-12/production"
    nodes = []
    for source in directory.glob("*.docx"):
        nodes.extend(build_section_documents(read_docx_text(source), source, "xml"))
    index = SectionEvidenceIndex(nodes)
    outcomes = []
    for question in ("Что ведется в договорных условиях?", "Как рассчитывается 2 ЦК по постановлениям?"):
        evidence = index.select(question, [])
        headings = [item["section_path"] for item in evidence]
        if "договорных" in question:
            required = ("Авансы", "Прогнозный", "Фактический", "Корректировочный", "округления", "Общие настройки")
            passed = all(any(term in heading for heading in headings) for term in required)
        else:
            passed = any(heading.endswith("Пункт 5") for heading in headings) and all("Постановление" in item["file"] for item in evidence)
        outcomes.append({"question": question, "passed": passed, "context": evidence})
    (directory / "section_selection_checks.json").write_text(json.dumps(outcomes, ensure_ascii=False, indent=2), encoding="utf-8")
    if not all(item["passed"] for item in outcomes):
        raise RuntimeError("Original-source section checks failed")
    return outcomes


